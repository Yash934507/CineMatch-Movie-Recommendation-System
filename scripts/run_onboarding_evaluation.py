def main():
    ratings, movies, _ = load_movielens(ROOT / "data" / "raw")
    metrics, details, summary = evaluate_onboarding(ratings, movies)
    summary["input_sha256"] = {name: hashlib.sha256((ROOT / "data" / "raw" / name).read_bytes()).hexdigest()
                               for name in ("ratings.csv", "movies.csv")}
    summary["versions"] = {name: importlib.metadata.version(name) for name in
                           ("numpy", "pandas", "scikit-surprise", "matplotlib")}
    summary["python_version"] = sys.version
    summary["protocol"] = {
        "training": "timestamp < fixed cutoff; evaluated users first timestamp >= cutoff",
        "cohorts": "seeded 50/50 disjoint new-user validation/test split before eligibility filtering",
        "chronology": "timestamp then movieId; first N; strictly later timestamps only",
        "candidates": "all later movies plus 100 unseen training items, uniform without replacement",
        "unknown_items": "fold-in global mean + user bias; popularity training global mean",
        "selection": "validation only, locked before test evaluation",
    }
    processed = ROOT / "data" / "processed"
    processed.mkdir(parents=True, exist_ok=True)
    metrics.to_csv(processed / "improvement2_onboarding_metrics.csv", index=False)
    details.to_csv(processed / "improvement2_user_details.csv", index=False)
    (processed / "improvement2_summary.json").write_text(json.dumps(summary, indent=2, allow_nan=False), encoding="utf-8")
    write_report(metrics, details, summary)
    save_chart(metrics)
    update_readme(metrics, summary)
    print(metrics.to_string(index=False))
    print(json.dumps(summary["product_policy"], indent=2))


if __name__ == "__main__":
    main()
